function normalizeStockText(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function normalizeColor(value: string): string {
  const normalized = normalizeStockText(value);
  if (normalized === "negra" || normalized === "negro") return "negro";
  if (normalized === "blanca" || normalized === "blanco") return "blanco";
  return normalized;
}

function normalizeModel(value?: string | null): GlobalStockPreset["garmentModel"] {
  const normalized = normalizeStockText(value ?? "");
  if (normalized.includes("long") && normalized.includes("sleeve")) return "long_sleeve_oversize";
  if (normalized.includes("regular")) return "regular";
  if (normalized.includes("hoodie")) return "hoodie";
  return "oversize";
}

function normalizeType(value?: string | null, model?: string | null): GlobalStockPreset["garmentType"] {
  const type = normalizeStockText(value ?? "");
  const modelKey = normalizeStockText(model ?? "");
  if (type.includes("hoodie") || modelKey.includes("hoodie")) return "hoodie";
  return "tshirt";
}

function normalizeFit(value?: string | null): GlobalStockPreset["fit"] {
  const normalized = normalizeStockText(value ?? "");
  if (normalized.includes("semi")) return "semi-oversize";
  if (normalized.includes("regular")) return "regular";
  return "oversize";
}

export function resolveGlobalStockPreset(input: {
  garmentType?: string | null;
  garmentModel?: string | null;
  color?: string | null;
  grammageG?: number | null;
  fit?: string | null;
}): GlobalStockPreset | null {
  const garmentType = normalizeType(input.garmentType, input.garmentModel);
  const garmentModel = normalizeModel(input.garmentModel);
  const color = normalizeColor(input.color ?? "");
  const fit = normalizeFit(input.fit);
  const grammageG = Number(input.grammageG ?? 0);

  for (const preset of GLOBAL_STOCK_PRESETS) {
    if (preset.garmentType !== garmentType) continue;
    if (preset.garmentModel !== garmentModel) continue;
    if (preset.grammageG !== grammageG) continue;
    if (normalizeColor(preset.color) !== color) continue;
    if (garmentType === "hoodie" && preset.fit !== fit) continue;
    return preset;
  }

  return null;
}
